/**
 * @fileoverview チャットカードの文字組み(共通)。
 *
 * カードは幅が狭い(~250px)ため、日本語は既定でどこでも改行される——その結果 ［完全死亡］ が
 * 「［完」「全死亡］」に割れる等、**ひとかたまりの語が途中で折れる**(2026-09-05 ユーザー指摘。
 * 同種の指摘はこれで複数回目のため、文言を短くする対症療法ではなく機構として解決する)。
 *
 * 対処は「折ってはいけない塊」を nowrap でくくること。塊とは**囲みで閉じた語**——
 * ［状態タグ］・《神業などのルール用語》・「名前」。長すぎる塊は逆にはみ出すので、
 * **カードの中で最も狭い段(対象名＋値の2列行)に収まる長さ(MAX_ATOMIC)まで**を対象にする
 * (それ以上は従来どおり折り返す——折らないと横にはみ出し、はみ出しの方が読めない)。
 *
 * **カードに文字列を組む箇所は必ずこの関数を通す**(各所で個別に nowrap を書かない)。
 */

/**
 * 折らない塊として扱う最大文字数(囲みの中身)。カードの2列行(対象名＋値)でも収まる長さにする——
 * 状態タグ(完全死亡=4)・よくある神業名(難攻不落=4・死の舞踏=4)はここに収まり、
 * 15文字級の長い固有名は従来どおり折り返す(2026-09-05 実機で調整)。
 */
const MAX_ATOMIC = 10;

/** 囲みで閉じた語: ［タグ］ / 《ルール用語》 / 「名前」。改行・入れ子は含まない。 */
const ATOMIC = new RegExp(`(［[^］\\n]{1,${MAX_ATOMIC}}］|《[^》\\n]{1,${MAX_ATOMIC}}》|「[^」\\n]{1,${MAX_ATOMIC}}」)`, "g");

/**
 * 囲みで閉じた語を途中で折らないよう nowrap でくくる。
 *
 * 引数は**組み立て済みの HTML 断片**(タグの属性値に ［］《》「」 を使わないこと——
 * このシステムの属性はクラス名・data-* だけなので満たしている)。
 * @param {string} html カードに差し込む HTML 断片
 * @returns {string} 折らない塊を `<span class="tnx-nobr">` でくくった HTML
 */
export function keepTogether(html) {
    return String(html ?? "").replace(ATOMIC, '<span class="tnx-nobr">$1</span>');
}
